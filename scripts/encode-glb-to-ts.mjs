#!/usr/bin/env node
// Final build pass: each self-contained zombie GLB (produced by
// embed-zombie-textures.mjs) gets emitted as a TypeScript module that
// exports the binary as chunked base64 strings. The runtime concatenates
// the chunks, atob-decodes to bytes, and feeds the buffer to GLTFLoader.
//
// We chunk to ~256 chars per array entry so the transport layer (MCP push)
// can't truncate any single string mid-run. Total source addition is around
// 3.4 MB across 17 modules.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(__dirname, '..', 'assets', 'characters', 'embedded');
const OUT = path.resolve(__dirname, '..', 'src', 'assets');

// Each character's base64 is split across multiple TS files so individual
// file size stays under ~40 KB — small enough that the chat-based push tool
// can carry them and the Read tool isn't capped. The registry concatenates
// all parts at runtime.
const CHUNK = 256;
const PARTS_PER_CHARACTER = 5;

async function emit(letter) {
  const inPath = path.join(SRC, `character${letter}.glb`);
  const buf = await fs.readFile(inPath);
  const b64 = buf.toString('base64');
  const chunks = [];
  for (let i = 0; i < b64.length; i += CHUNK) {
    chunks.push(b64.slice(i, i + CHUNK));
  }
  const partSize = Math.ceil(chunks.length / PARTS_PER_CHARACTER);
  let totalChunks = 0;
  const partExports = [];
  for (let p = 0; p < PARTS_PER_CHARACTER; p++) {
    const slice = chunks.slice(p * partSize, (p + 1) * partSize);
    if (slice.length === 0) continue;
    totalChunks += slice.length;
    const lines = slice.map((c) => `  '${c}',`).join('\n');
    const constName = `CHARACTER_${letter.toUpperCase()}_B64_${p + 1}`;
    const code =
      `// AUTO-GENERATED by scripts/encode-glb-to-ts.mjs — do not edit by hand.\n` +
      `// Part ${p + 1}/${PARTS_PER_CHARACTER} of character ${letter}.glb (~${Math.round(slice.length * CHUNK / 1024)} KB).\n` +
      `export const ${constName}: readonly string[] = [\n` +
      `${lines}\n` +
      `];\n`;
    const outPath = path.join(OUT, `character-${letter}-${p + 1}.ts`);
    await fs.writeFile(outPath, code);
    partExports.push(constName);
  }
  // Aggregator file: concatenates the parts into a single chunk array.
  const partImports = partExports
    .map((n, i) => `import { ${n} } from './character-${letter}-${i + 1}';`)
    .join('\n');
  const partList = partExports.map((n) => `  ...${n},`).join('\n');
  const aggCode =
    `// AUTO-GENERATED by scripts/encode-glb-to-ts.mjs — do not edit by hand.\n` +
    `// Aggregator for character ${letter}: concatenates the part arrays.\n` +
    `${partImports}\n\n` +
    `export const CHARACTER_${letter.toUpperCase()}_B64_CHUNKS: readonly string[] = [\n` +
    `${partList}\n` +
    `];\n`;
  const aggPath = path.join(OUT, `character-${letter}.ts`);
  await fs.writeFile(aggPath, aggCode);
  console.log(`  ${letter}: ${totalChunks} chunks across ${partExports.length} parts → character-${letter}{,-1..${partExports.length}}.ts`);
}

async function main() {
  await fs.mkdir(OUT, { recursive: true });
  const files = await fs.readdir(SRC);
  const letters = files
    .map((f) => f.match(/^character([a-z])\.glb$/))
    .filter(Boolean)
    .map((m) => m[1])
    .sort();
  console.log(`Encoding ${letters.length} embedded GLBs as TS modules:`);
  for (const letter of letters) {
    await emit(letter);
  }
  console.log('done.');
}

main().catch((e) => { console.error(e); process.exit(1); });
