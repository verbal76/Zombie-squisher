import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const OUTPUT = 'src/__generated__/build-info.ts';

const git = (cmd, fallback = '') => {
  try { return execSync(`git ${cmd}`, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); }
  catch { return fallback; }
};

// CI-provided identity wins (it is correct even when .git is not present, e.g. EAS local builds).
const env = process.env;
const branch       = env.GITHUB_REF_NAME || git('rev-parse --abbrev-ref HEAD', 'unknown');
const commit       = env.GITHUB_SHA || git('rev-parse HEAD', 'unknown');
const commitShort  = commit === 'unknown' ? 'unknown' : commit.slice(0, 7);
// The generated file itself is always modified in CI, so it must not count as "dirty".
const dirty        = git(`status --porcelain -- . ":!${OUTPUT}"`) !== '';
const builtAt      = new Date().toISOString();
const ciRun        = env.GITHUB_RUN_NUMBER ? Number(env.GITHUB_RUN_NUMBER) : null;

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const app = JSON.parse(readFileSync('app.json', 'utf8'));
const gameName           = app?.expo?.name ?? 'Zombie Squisher';
const appVersion         = pkg.version ?? app?.expo?.version ?? 'unknown';
const androidVersionCode = app?.expo?.android?.versionCode ?? null;
const apkFileName        = `${gameName.trim().replace(/[^A-Za-z0-9]+/g, '-').replace(/^-+|-+$/g, '')}-v${app?.expo?.version ?? appVersion}.apk`;

const buildId = `build ${commitShort} (${branch})${dirty ? ' [dirty]' : ''}`;
const otaId   = `OTA ${commitShort} @ ${builtAt}`;

const data = {
  gameName, branch, commit, commitShort, dirty, builtAt,
  appVersion, androidVersionCode, ciRun, apkFileName,
  buildId, otaId,
};

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT,
  `// AUTO-GENERATED by scripts/write-build-info.mjs. Do not edit.\n` +
  `export interface BuildInfo {\n` +
  `  gameName: string; branch: string; commit: string; commitShort: string;\n` +
  `  dirty: boolean; builtAt: string;\n` +
  `  appVersion: string; androidVersionCode: number | null;\n` +
  `  ciRun: number | null; apkFileName: string;\n` +
  `  buildId: string; otaId: string;\n` +
  `}\n` +
  `export const BUILD_INFO: BuildInfo = ${JSON.stringify(data, null, 2)};\n`
);

console.log(`write-build-info: ${gameName} v${appVersion} (code ${androidVersionCode}) ${branch}@${commitShort}${dirty ? ' (dirty)' : ''} -> ${apkFileName}`);
