// Generates THIRD_PARTY_NOTICES.md for the JavaScript packages that are actually bundled into the app (Android
// Hermes bundle and the web/desktop bundle). The package list (tools/notice-packages.json) comes from the Metro
// source maps:   node tools/generate-notices.mjs --scan   (runs both exports, slow; re-run after dependency changes)
// Texts come only from each installed package's own license file and metadata; nothing is written from memory.
//   node tools/generate-notices.mjs            write THIRD_PARTY_NOTICES.md
//   node tools/generate-notices.mjs --check    fail if the committed file is out of date
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const LIST = path.join(root, 'tools/notice-packages.json');
const OUT = path.join(root, 'THIRD_PARTY_NOTICES.md');

if (process.argv.includes('--scan')) {
  const tmp = fs.mkdtempSync(path.join(process.env.TMPDIR || '/tmp', 'notice-scan-'));
  const found = {};
  for (const platform of ['web', 'android']) {
    execFileSync('npx', ['expo', 'export', '--platform', platform, '--dump-sourcemap', '--clear', '--output-dir', path.join(tmp, platform)], { stdio: 'ignore', env: { ...process.env, CI: '1' } });
    const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
    for (const f of walk(path.join(tmp, platform)).filter((x) => x.endsWith('.map'))) {
      for (const s of JSON.parse(fs.readFileSync(f, 'utf8')).sources) {
        const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(s);
        if (m) (found[m[1]] ??= new Set()).add(platform);
      }
    }
  }
  fs.writeFileSync(LIST, JSON.stringify(Object.fromEntries(Object.keys(found).sort().map((k) => [k, [...found[k]].sort()])), null, 1) + '\n');
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`scanned: ${Object.keys(found).length} bundled packages -> tools/notice-packages.json`);
}

const list = JSON.parse(fs.readFileSync(LIST, 'utf8'));
const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'license', 'license.md', 'License.md', 'COPYING', 'LICENSE-MIT', 'LICENSE-MIT.txt'];

// License texts for packages whose npm tarball ships none: the upstream repository's own LICENSE, vendored with its
// source URL and retrieval date in tools/license-texts/sources.json (never written from memory).
const UPSTREAM = [[/github\.com\/expo\/expo/, 'expo.LICENSE'], [/github\.com\/facebook\/react-native/, 'react-native.LICENSE'], [/github\.com\/pmndrs\/react-three-fiber/, 'react-three-fiber.LICENSE']];
const upstreamSources = JSON.parse(fs.readFileSync(path.join(root, 'tools/license-texts/sources.json'), 'utf8'));

function describe(name) {
  const dir = path.join(root, 'node_modules', name);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNSPECIFIED');
  const file = LICENSE_FILES.map((f) => path.join(dir, f)).find((f) => fs.existsSync(f));
  let text = file ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim() : null;
  const repoUrl = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '';
  let upstream = null;
  if (!text) {
    const hit = UPSTREAM.find(([re]) => re.test(repoUrl));
    if (hit) { text = fs.readFileSync(path.join(root, 'tools/license-texts', hit[1]), 'utf8').replace(/\r\n/g, '\n').trim(); upstream = upstreamSources[hit[1]]; }
  }
  const copyright = text ? [...new Set(text.split('\n').map((l) => l.trim()).filter((l) => /^(copyright|\(c\)|©)/i.test(l)))] : [];
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
  return { name, version: pkg.version, license: lic, text, upstream, copyright, repo: repo.replace(/^git\+/, '').replace(/\.git$/, ''), platforms: list[name] };
}

const pkgs = Object.keys(list).sort().map(describe);
const groups = new Map();
for (const p of pkgs) {
  const key = p.text ? crypto.createHash('sha256').update(p.text.replace(/^.*copyright.*$/gim, '')).digest('hex') : 'none';
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(p);
}

let md = `# Third-party notices

Zombie Squisher (c) Hot Attic Games. It bundles the open-source JavaScript packages listed below. This file is generated by
\`tools/generate-notices.mjs\` from the package metadata and license files installed in \`node_modules\` (the package list comes from the
Metro source maps of the Android and web/desktop bundles). Regenerate after any dependency change; \`npm test\` fails if it is stale.

Desktop (Windows/Linux) builds additionally ship Electron and Chromium: see \`LICENSE.electron.txt\` and \`LICENSES.chromium.html\` inside every desktop package.
Assets (3D models, audio, glyphs, logo) are covered separately in \`docs/THIRD_PARTY_ASSETS.md\`.

## Summary

| Package | Version | License (package metadata) | Bundled in |
|---|---|---|---|
${pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.platforms.join(', ')} |`).join('\n')}

## Copyright notices and license texts

Packages with identical license wording share one text; each package's own copyright line(s) are kept.
`;
let n = 0;
for (const [key, members] of [...groups.entries()].sort((a, b) => b[1].length - a[1].length || a[1][0].name.localeCompare(b[1][0].name))) {
  n++;
  md += `\n### ${key === 'none' ? 'Packages without a license file in their package' : `License text ${n}`}\n\n`;
  for (const p of members) {
    md += `- **${p.name}** ${p.version} (${p.license})${p.repo ? ` - ${p.repo}` : ''}${p.upstream ? ` - text from the upstream repository (${p.upstream.url}, retrieved ${p.upstream.retrieved}); the npm package ships no license file` : ''}\n`;
    for (const c of p.copyright) md += `  - ${c}\n`;
  }
  if (key === 'none') md += `\nThese packages declare the licenses shown in the table in their package.json but ship no license file and no vendored upstream text is available: confirm against each repository before commercial release.\n`;
  else md += `\n\`\`\`text\n${members[0].text}\n\`\`\`\n`;
}
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== md) { console.error('THIRD_PARTY_NOTICES.md is out of date: run `node tools/generate-notices.mjs`'); process.exit(1); }
  console.log('notices up to date');
} else {
  fs.writeFileSync(OUT, md);
  console.log(`wrote THIRD_PARTY_NOTICES.md: ${pkgs.length} packages, ${groups.size} distinct license texts, ${pkgs.filter((p) => !p.text).length} without a license file`);
}
